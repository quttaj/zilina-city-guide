CREATE TABLE IF NOT EXISTS users (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 isAdmin TINYINT NOT NULL DEFAULT 0
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS places (
 id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(255) NOT NULL UNIQUE, description TEXT NOT NULL,
 image_path VARCHAR(1024) DEFAULT NULL
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS comments (
 id VARCHAR(36) NOT NULL PRIMARY KEY, name VARCHAR(255) NOT NULL,
 description TEXT NOT NULL, author_id INT NOT NULL,
 parent_id VARCHAR(36) DEFAULT NULL, reply_count INT NOT NULL DEFAULT 0,
 view_count INT NOT NULL DEFAULT 0, file_path VARCHAR(1024) DEFAULT NULL,
 INDEX (parent_id), INDEX (author_id)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS attachments (
 id VARCHAR(64) NOT NULL PRIMARY KEY, comment_id VARCHAR(36) NOT NULL,
 content MEDIUMBLOB NOT NULL, INDEX (comment_id)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
